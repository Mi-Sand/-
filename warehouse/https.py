"""Перенаправление на HTTPS, из которого можно вернуться.

Django на обращение по http отвечает «301 Moved Permanently» — переехало
навсегда. Браузеры такой ответ запоминают насовсем: Chrome, Firefox и
Edge больше никогда не постучатся по http на этот адрес, даже после
очистки настроек на сервере.

Для сайта в интернете это правильно. Для системы, которая живёт на
офисном компьютере, — ловушка, и она захлопывается по-настоящему.
Достаточно один раз включить USE_HTTPS=True раньше, чем заработает
сертификат: браузер запомнит перенаправление, а идти ему станет некуда —
сервер разработки говорит только по http. Вход закрыт, и выключение
USE_HTTPS обратно уже не помогает: решение принимает браузер, до
обращения к серверу. Разбирать это приходится через chrome://net-internals
и очистку кэша — то есть силами того, кто вообще знает, что это такое.

Поэтому здесь перенаправление временное («302 Found»). Браузер выполняет
его точно так же, но не запоминает: выключили USE_HTTPS — и следующий же
запрос открывается как обычно, без плясок с настройками браузера.

Постоянство, ради которого нужен 301, при работающем HTTPS даёт
заголовок HSTS: он в этом же посреднике и включается вместе с
шифрованием. Так что защита не слабеет — просто ошибка перестаёт быть
необратимой.
"""
from django.http import HttpResponsePermanentRedirect, HttpResponseRedirect
from django.middleware.security import SecurityMiddleware


class RecoverableSecurityMiddleware(SecurityMiddleware):
    """Тот же посредник безопасности, но с временным перенаправлением."""

    def process_request(self, request):
        response = super().process_request(request)
        if isinstance(response, HttpResponsePermanentRedirect):
            # Тот же адрес, тот же смысл — меняется только пометка
            # «навсегда» на «пока что»
            return HttpResponseRedirect(response['Location'])
        return response
