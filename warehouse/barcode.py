"""Штрихкод Code 128 — рисуется сам, без посторонних библиотек.

Зачем свой. Готовые библиотеки тянут за собой зависимости и требуют
интернета при установке, а система ставится на складской компьютер,
которого в интернете нет. Здесь всего-то нужно превратить строку в
набор полос: сорок строк кода против ещё одной внешней зависимости.

Почему Code 128. Он берёт и цифры, и латиницу, читается любым дешёвым
сканером и на узкой этикетке умещается лучше, чем EAN-13, который к
тому же требует покупки диапазона номеров у регистратора.

Кириллицу штрихкод не берёт — ни один не берёт. Поэтому в код идёт
артикул или внутренний номер, а название печатается рядом словами.
"""

#: Ширины полос для каждого значения Code 128. Обычно шесть чисел:
#: полоса, пробел, полоса, пробел, полоса, пробел; у знака остановки
#: семь. Таблица стандартная и менять её нельзя — сканер знает её
#: наизусть.
PATTERNS = [
    '212222', '222122', '222221', '121223', '121322', '131222', '122213',
    '122312', '132212', '221213', '221312', '231212', '112232', '122132',
    '122231', '113222', '123122', '123221', '223211', '221132', '221231',
    '213212', '223112', '312131', '311222', '321122', '321221', '312212',
    '322112', '322211', '212123', '212321', '232121', '111323', '131123',
    '131321', '112313', '132113', '132311', '211313', '231113', '231311',
    '112133', '112331', '132131', '113123', '113321', '133121', '313121',
    '211331', '231131', '213113', '213311', '213131', '311123', '311321',
    '331121', '312113', '312311', '332111', '314111', '221411', '431111',
    '111224', '111422', '121124', '121421', '141122', '141221', '112214',
    '112412', '122114', '122411', '142112', '142211', '241211', '221114',
    '413111', '241112', '134111', '111242', '121142', '121241', '114212',
    '124112', '124211', '411212', '421112', '421211', '212141', '214121',
    '412121', '111143', '111341', '131141', '114113', '114311', '411113',
    '411311', '113141', '114131', '311141', '411131', '211412', '211214',
    '211232',
    # Знак остановки — единственный из семи полос, а не из шести: он и
    # даёт сканеру понять, что код кончился. Сумма его модулей 13, у
    # остальных 11.
    '2331112',
]

START_B = 104
STOP = 106

#: Что печатается на этикетке. Больше сканер и не прочтёт с узкой
#: полосы, а длинный код мельчит полосы до неразличимости.
MAX_LENGTH = 32


class BarcodeError(ValueError):
    """Строку нельзя превратить в штрихкод."""


def values(text):
    """Перевести строку в значения Code 128 (набор B).

    Набор B взят один на все случаи: он покрывает цифры, латиницу и
    знаки. Переключение на набор C ради экономии двух полос усложнило
    бы разбор вдвое.
    """
    if not text:
        raise BarcodeError('Штрихкод пуст.')
    if len(text) > MAX_LENGTH:
        raise BarcodeError(
            f'Слишком длинный штрихкод: {len(text)} знаков, '
            f'печатается не больше {MAX_LENGTH}.')

    codes = []
    for letter in text:
        number = ord(letter)
        if not 32 <= number <= 126:
            raise BarcodeError(
                f'Знак «{letter}» в штрихкод не кодируется. Годятся '
                f'цифры, латинские буквы и знаки препинания — русские '
                f'буквы не берёт ни один штрихкод.')
        codes.append(number - 32)
    return codes


def widths(text):
    """Ширины всех полос и пробелов по порядку."""
    codes = values(text)
    # Контрольное число: без него сканер примет за код любую грязь на
    # этикетке. Считается как сумма с весами по положению.
    total = START_B + sum((position + 1) * code
                          for position, code in enumerate(codes))
    checksum = total % 103

    sequence = [START_B, *codes, checksum, STOP]
    result = []
    for value in sequence:
        result.extend(int(width) for width in PATTERNS[value])
    return result


def svg(text, height=42, module=1.6, caption=None, quiet=10):
    """Нарисовать штрихкод разметкой SVG.

    Рисунок вставляется прямо в страницу: отдельным файлом его пришлось
    бы просить с сервера, а печать этикеток нередко идёт с компьютера,
    который в эту минуту с сервером не разговаривает.

    `module` — ширина самой узкой полосы в точках. Меньше 1.2 сканеры
    начинают ошибаться на обычной бумаге, поэтому здесь 1.6.
    """
    bars = widths(text)
    width = sum(bars) * module + quiet * 2
    lines = []
    position = quiet
    dark = True                      # первая полоса всегда чёрная
    for bar in bars:
        length = bar * module
        if dark:
            lines.append(
                f'<rect x="{position:.2f}" y="0" '
                f'width="{length:.2f}" height="{height}" fill="#000"/>')
        position += length
        dark = not dark

    text_height = 13 if caption is not False else 0
    label = ''
    if caption is not False:
        shown = caption if caption else text
        label = (f'<text x="{width / 2:.2f}" y="{height + 11}" '
                 f'text-anchor="middle" font-family="monospace" '
                 f'font-size="11">{escape(shown)}</text>')

    return (f'<svg xmlns="http://www.w3.org/2000/svg" '
            f'width="{width:.2f}" height="{height + text_height}" '
            f'viewBox="0 0 {width:.2f} {height + text_height}">'
            f'{"".join(lines)}{label}</svg>')


def escape(value):
    """Экранировать текст подписи.

    Подпись берётся из названия товара, а его вводит человек: символ
    «<» без обработки сломал бы разметку всей этикетки.
    """
    return (str(value).replace('&', '&amp;').replace('<', '&lt;')
            .replace('>', '&gt;').replace('"', '&quot;'))


def suggest(prefix, number):
    """Придумать штрихкод для позиции, у которой его нет.

    Внутренний номер, а не купленный у регистратора: для учёта на своём
    складе этого достаточно, а покупка диапазона нужна только тем, кто
    отдаёт товар в чужие магазины.
    """
    return f'{prefix}{int(number):08d}'
