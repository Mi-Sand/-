"""
Сведения о предприятии для публичных страниц магазина.

# ===========================================================================
#  ЗАПОЛНИТЕ ЭТОТ ФАЙЛ
# ===========================================================================
#
#  Здесь собраны все контакты, которые видит покупатель: адрес, телефон,
#  почта, часы работы, реквизиты. Правится одно место — меняется сразу на
#  всех страницах: в шапке, в подвале, на странице «Контакты» и в схеме
#  проезда.
#
#  Значения с пометкой ЗАПОЛНИТЬ — заглушки. Я не знаю настоящих телефона,
#  улицы и ИНН предприятия и не стал их выдумывать: выдуманный ИНН на
#  публичной странице хуже, чем его отсутствие. Пока поле не заполнено,
#  строка на сайте не выводится вовсе — пустых строк покупатель не увидит.
#
#  После правки перезапустите сервер: этот файл читается один раз при
#  запуске.
# ===========================================================================
"""

# Пометка незаполненного поля. Строки, равные ей, на сайт не попадают.
FILL = 'ЗАПОЛНИТЬ'


COMPANY = {
    # --- Название -----------------------------------------------------------
    'short_name': 'ООО «ЛЕКО»',
    'full_name': 'Общество с ограниченной ответственностью «ЛЕКО»',

    # --- Чем занимается ------------------------------------------------------
    'tagline': 'Производство спортивного инвентаря и экипировки',
    'city': 'г. Дмитров',
    'region': 'Московская область',

    # --- Адрес ---------------------------------------------------------------
    # Улица и дом. Например: 'ул. Промышленная, д. 12, строение 3'
    'street': FILL,
    # Как найти вход: 'въезд со стороны улицы, второй корпус, вывеска на фасаде'
    'how_to_find': FILL,

    # --- Связь ---------------------------------------------------------------
    # Телефон в виде, удобном для чтения: '+7 (495) 123-45-67'
    'phone': FILL,
    # Тот же телефон только цифрами, для кнопки «позвонить»: '+74951234567'
    'phone_link': FILL,
    'email': FILL,

    # --- Часы работы ---------------------------------------------------------
    'hours_week': 'Пн–Пт, 9:00–18:00',
    'hours_weekend': 'Сб, Вс — выходной',

    # --- Реквизиты (нужны для счетов и договоров) ----------------------------
    'inn': FILL,
    'kpp': FILL,
    'ogrn': FILL,

    # --- Координаты для схемы проезда ----------------------------------------
    # Широта и долгота площадки. Взять можно в любых картах: найдите здание,
    # нажмите на него правой кнопкой — координаты покажутся в подсказке.
    # Формат: строка вида '56.344500, 37.520300'
    'coords': FILL,
}


def is_filled(value):
    """Заполнено ли поле. Пустое и заглушка считаются незаполненными."""
    return bool(value) and value != FILL


def company_context(request):
    """Отдаёт сведения о предприятии всем публичным страницам.

    Подключается как процессор контекста, поэтому в шаблонах доступно
    просто {{ company.phone }} — передавать вручную из каждого view не
    нужно.
    """
    data = dict(COMPANY)
    # Полный адрес одной строкой — он нужен и в подвале, и в картах.
    parts = [data['region'], data['city']]
    if is_filled(data['street']):
        parts.append(data['street'])
    data['address_full'] = ', '.join(parts)
    # Готовые признаки заполненности: в шаблоне «если» по ним читается
    # лучше, чем сравнение со словом-заглушкой.
    for field in ('street', 'phone', 'phone_link', 'email', 'inn', 'kpp',
                  'ogrn', 'coords', 'how_to_find'):
        data['has_' + field] = is_filled(data[field])
    return {'company': data}
