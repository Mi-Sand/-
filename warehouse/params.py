"""Чтение параметров запроса, которым нельзя доверять.

Отбор на странице задаёт человек через поля и календарь, но до
обработчика доходит просто строка — и прийти она может откуда угодно.
Каждый такой разбор уже однажды ронял систему: нечисловой номер склада,
номер шире разрядности базы, дата вида «2020-13-45». Поэтому разбор
собран в одном месте и проверен тестами, а не написан заново в каждом
обработчике.

Общее правило: негодное значение не ошибка, а отсутствие отбора. Пустой
список понятнее страницы с отказом, а объяснить человеку, что он ввёл
не ту дату, лучше подсказкой рядом с полем.
"""
from django.db.models import Q
from django.utils.dateparse import parse_date

#: Наибольшее целое, какое принимает база. Число шире SQLite не
#: сравнивает, а падает на самом запросе.
MAX_ID = 2 ** 63 - 1


def read_date(value):
    """Дата из строки или None.

    `parse_date` на строке вида «2020-13-45» не возвращает None, а
    бросает ValueError: вид верный, а месяца такого нет.
    """
    try:
        return parse_date(value or '')
    except ValueError:
        return None


def contains_any_case(field, term):
    """Условие «поле содержит term» без оглядки на регистр букв.

    Казалось бы, для этого есть `icontains` — но в SQLite он приводит
    к одному регистру только латиницу. «кожа» не находило «Кожа
    хромовая», и человек делал вывод, что документа нет. Отдельно
    неприятно, что на PostgreSQL то же самое работало бы правильно:
    ошибка проявилась бы только у заказчика.

    Поэтому ищем сразу несколько написаний слова. Полного разбора
    регистра это не даёт (внутри слова буквы остаются как есть), но
    закрывает всё, что люди набирают на самом деле: строчными,
    прописными или с большой буквы.
    """
    wordings = {term, term.lower(), term.upper(), term.capitalize()}
    condition = Q(**{f'{field}__icontains': term})
    for wording in wordings:
        condition |= Q(**{f'{field}__contains': wording})
    return condition


def read_id(value):
    """Номер записи из строки или None, если это не номер."""
    if not value or not str(value).isdigit():
        return None
    number = int(value)
    return number if 0 < number <= MAX_ID else None
