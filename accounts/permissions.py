"""
Права доступа по ролям сотрудников.

Роли в системе были и раньше — поле у пользователя и свойства вроде
`can_edit_documents` в модели. Но ни одна проверка на них не ссылалась:
любой вошедший сотрудник мог делать всё, включая правку справочников и
проведение документов. Здесь эти свойства наконец получают применение.

Общий принцип: **читать может любой вошедший сотрудник, изменять — только
тот, чья роль это предполагает.** Складской учёт — не то место, где стоит
прятать друг от друга данные: менеджеру полезно видеть остатки, а
кладовщику — цены. Опасны не просмотры, а изменения: проведённый не тем
человеком документ меняет остатки, и обнаруживается это через недели, при
инвентаризации.

Поэтому все классы ниже пропускают безопасные методы (GET, HEAD, OPTIONS)
и проверяют роль только на изменяющих (POST, PUT, PATCH, DELETE).
Действия вроде «провести документ» тоже выполняются методом POST и потому
попадают под проверку автоматически.

Суперпользователь проходит везде: это учётная запись для обслуживания
системы, и запирать её от собственных данных бессмысленно.
"""
from rest_framework.permissions import SAFE_METHODS, BasePermission


class RoleBasedPermission(BasePermission):
    """Основа для проверок: чтение всем, изменение — по свойству роли.

    Наследники задают `user_flag` — имя свойства модели пользователя,
    и `message` — что показать при отказе. Сообщение важно: «У вас
    недостаточно прав» заставляет гадать, а «Изменять справочники может
    экономист или кладовщик» сразу говорит, к кому идти.
    """

    user_flag = None
    message = 'У вашей роли нет прав на это действие.'

    def has_permission(self, request, view):
        user = request.user
        if not (user and user.is_authenticated):
            return False
        if request.method in SAFE_METHODS:
            return True
        if user.is_superuser:
            return True
        return bool(getattr(user, self.user_flag, False))


class CanManageCatalog(RoleBasedPermission):
    """Ведение справочников: материалы, продукция, склады, поставщики."""

    user_flag = 'can_manage_catalog'
    message = ('Изменять справочники могут экономист, кладовщик или '
               'администратор.')


class CanEditDocuments(RoleBasedPermission):
    """Документы склада: приход, расход, проведение, сторно, производство.

    Сюда же отнесена инвентаризация: её завершение меняет остатки так же,
    как проведение документа.
    """

    user_flag = 'can_edit_documents'
    message = ('Работать со складскими документами могут кладовщик или '
               'администратор.')


class CanProcessOrders(RoleBasedPermission):
    """Обработка заказов покупателей: подтверждение и отмена."""

    user_flag = 'can_process_orders'
    message = ('Обрабатывать заказы могут менеджер, кладовщик или '
               'администратор.')


class IsAdminRole(BasePermission):
    """Только администратор или суперпользователь.

    В отличие от классов выше, закрывает и чтение: список сотрудников с
    их ролями — не то, что нужно видеть каждому.
    """

    message = 'Раздел доступен только администратору.'

    def has_permission(self, request, view):
        user = request.user
        if not (user and user.is_authenticated):
            return False
        return user.is_superuser or getattr(user, 'role', None) == 'admin'
